/**
 * Writes supabase/seed.sql from the sample listings in src/lib/seed.
 * Run: npx tsx scripts/generate-seed.ts
 */
import { writeFileSync } from "node:fs";
import { seedProperties } from "../src/lib/seed/properties";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(q).join(", ")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const cols = [
  "slug", "title", "listing_type", "property_type", "status", "price", "price_period", "price_on_request",
  "state", "city", "area", "address", "bedrooms", "bathrooms", "toilets", "parking", "size_sqm",
  "title_document", "description", "features", "images", "featured", "published", "verified", "created_at",
];

const rows = seedProperties.map((p) =>
  `  (${[
    p.slug, p.title, p.listingType, p.propertyType, p.status, p.price, p.pricePeriod, p.priceOnRequest,
    p.state, p.city, p.area, p.address, p.bedrooms, p.bathrooms, p.toilets, p.parking, p.sizeSqm,
    p.titleDocument, p.description, p.features, p.images, p.featured, p.published, p.verified, p.createdAt,
  ].map((v) => (Array.isArray(v) && v.length === 0 ? "'{}'::text[]" : q(v))).join(", ")})`,
);

const sql = `-- Sample Nigerian listings (generated by scripts/generate-seed.ts). Safe to re-run.
insert into public.properties (${cols.join(", ")})
values
${rows.join(",\n")}
on conflict (slug) do nothing;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote ${seedProperties.length} properties to supabase/seed.sql`);
